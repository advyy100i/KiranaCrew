"""Render eval/results/*.json into markdown tables:  python eval/make_report.py > docs/eval_tables.md"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROWS = ["rules", "llm_ollama_qwen2.5-3b", "llm_groq_qwen3.8-27b", "hybrid_ollama_qwen2.5-3b", "hybrid_groq_qwen3.8-27b"]
LABEL = {"rules": "rules only (no network)", "llm_ollama_qwen2.5-3b": "LLM only — local qwen2.5:3b (Ollama, GPU)",
         "llm_groq_qwen3.8-27b": "LLM only — hosted qwen3.8-27b (Groq)", "hybrid_ollama_qwen2.5-3b": "hybrid — rules → local qwen2.5:3b",
         "hybrid_groq_qwen3.8-27b": "hybrid — rules → hosted qwen3.8-27b"}


def pct(a, b):
    return f"{100 * a / b:.1f}%" if b else "n/a"


def table(ds: str) -> str:
    out = [f"### {ds} ({'130 examples, written alongside the rules' if ds == 'dataset' else '55 examples, held out'})", "",
           "| parser | end-to-end | field-level | type | confirmation rate | ask precision / recall | **false updates** | parser split | p50 / p95 ms |",
           "|---|---|---|---|---|---|---|---|---|"]
    for r in ROWS:
        f = HERE / "results" / f"{ds}_{r}.json"
        if not f.exists():
            out.append(f"| {LABEL[r]} | _not run_ | | | | | | | |"); continue
        d = json.loads(f.read_text(encoding="utf-8")); m = d["metrics"]
        pf = d["per_field"]; fc = sum(v[0] for v in pf.values()); ft = sum(v[1] for v in pf.values())
        split = ", ".join(f"{k} {v}" for k, v in sorted(d["parser_split"].items()))
        out.append(f"| {LABEL[r]} | {pct(m['e2e'], m['n'])} | {pct(fc, ft)} | {pct(m['type_correct'], m['type_total'])} | "
                   f"{pct(m.get('asked', 0), m['n'])} | {pct(m.get('asked_and_gold_ask', 0), m.get('asked', 0))} / {pct(m.get('asked_and_gold_ask', 0), m.get('gold_ASK', 0))} | "
                   f"**{m.get('false_updates', 0)}** ({pct(m.get('false_updates', 0), m['n'])}) | {split} | {m['p50_ms']} / {m['p95_ms']} |")
    return "\n".join(out)


def errors(ds: str) -> str:
    out = []
    for r in ROWS:
        f = HERE / "results" / f"{ds}_{r}.json"
        if not f.exists():
            continue
        d = json.loads(f.read_text(encoding="utf-8"))
        for e in d["errors"]:
            g, p = e["gold"], e["pred"]
            gold = g["action"] + (":" + (g.get("ask_reason") or g.get("reject_reason") or "") if g["action"] != "COMMIT" else
                                  f" {g.get('type')} {g.get('amount_paise')}")
            pred = p["action"] + (":" + (p["reason"] or "") if p["action"] != "COMMIT" else f" {p['type']} {p['amount_paise']}")
            flag = " ⚠️ FALSE UPDATE" if p["action"] == "COMMIT" else ""
            out.append(f"| {LABEL[r]} | {e['id']} | {e['text']} | {gold} | {pred}{flag} |")
    if not out:
        return ""
    return "\n".join([f"#### misses on {ds}", "", "| parser | id | text | gold | predicted |", "|---|---|---|---|---|"] + out)


if __name__ == "__main__":
    print(f"_generated by eval/make_report.py from eval/results/ on {__import__('time').strftime('%Y-%m-%d')}_\n")
    for ds in ("heldout", "dataset"):
        print(table(ds)); print(); print(errors(ds)); print()
    stt = HERE / "results" / "stt_bench.json"
    if stt.exists():
        d = json.loads(stt.read_text(encoding="utf-8"))
        print("### STT (eval/audio, jiwer)\n\n| provider | model | clips | CER | WER | CER after normalize | p50 ms | p95 ms |\n|---|---|---|---|---|---|---|---|")
        for k, v in d.items():
            print(f"| {k} | {v['model']} | {v['n']} | {v['cer']:.3f} | {v['wer']:.3f} | {v['norm_cer']:.3f} | {v['p50_ms']} | {v['p95_ms']} |")
